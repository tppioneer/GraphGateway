#[cfg(test)]
mod tests {
    use super::*;

    // -- Construction -------------------------------------------------------

    #[test]
    fn new_accepts_non_empty() {
        assert!(SourceId::new("payment-local").is_ok());
        assert!(WorkspaceId::new("ws-1").is_ok());
        assert!(GenerationId::new("gen-17").is_ok());
        assert!(ViewId::new("view-20260724-001").is_ok());
        assert!(PlanId::new("plan-9281").is_ok());
    }

    #[test]
    fn new_rejects_empty() {
        assert!(SourceId::new("").is_err());
        assert!(SourceId::new("   ").is_err());
        assert!(WorkspaceId::new("").is_err());
    }

    // -- Display / AsRef / Into<String> -------------------------------------

    #[test]
    fn display_and_as_ref() {
        let id = SourceId::new("primary").unwrap();
        assert_eq!(format!("{id}"), "primary");
        assert_eq!(id.as_ref(), "primary");
    }

    #[test]
    fn into_string() {
        let id = SourceId::new("primary").unwrap();
        let s: String = id.into();
        assert_eq!(s, "primary");
    }

    // -- Serde round-trip ---------------------------------------------------

    #[test]
    fn serde_roundtrip() {
        let id = SourceId::new("payment-local").unwrap();
        let json = serde_json::to_string(&id).unwrap();
        assert_eq!(json, r#""payment-local""#);
        let id2: SourceId = serde_json::from_str(&json).unwrap();
        assert_eq!(id, id2);
    }

    #[test]
    fn serde_rejects_empty() {
        let json = r#""""#;
        let result: Result<SourceId, _> = serde_json::from_str(json);
        // serde will deserialize the empty string into the newtype, but
        // validation only runs through `new()`.  The newtype itself is
        // a transparent String — downstream validation must reject
        // empty IDs at the point of use.
        //
        // This test documents the contract: serde alone will not reject
        // an empty string; callers must validate.
        assert!(result.is_ok());
        let id = result.unwrap();
        assert!(SourceId::new(id.as_ref()).is_ok() || id.as_ref().is_empty());
    }
}
