//! Strongly-typed identifiers for the domain model.
//!
//! Each ID type is a newtype wrapper over `String`, preventing accidental
//! interchange of different ID kinds (e.g. a [`SourceId`] cannot be
//! silently passed where a [`WorkspaceId`] is expected).
//!
//! All IDs must be non-empty; constructors return an error for empty strings.

use serde::{Deserialize, Serialize};

macro_rules! define_id {
    (
        $(#[$attr:meta])*
        $name:ident
    ) => {
        $(#[$attr])*
        #[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
        #[serde(transparent)]
        pub struct $name(String);

        impl $name {
            /// Create a new ID, rejecting empty strings.
            ///
            /// Returns `Err` with a human-readable message when `value` is empty
            /// or whitespace-only.
            pub fn new(value: impl Into<String>) -> Result<Self, String> {
                let v = value.into();
                if v.trim().is_empty() {
                    return Err(format!("{} must not be empty", stringify!($name)));
                }
                Ok(Self(v))
            }
        }

        impl std::fmt::Display for $name {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                f.write_str(&self.0)
            }
        }

        impl AsRef<str> for $name {
            fn as_ref(&self) -> &str {
                &self.0
            }
        }

        impl From<$name> for String {
            fn from(id: $name) -> Self {
                id.0
            }
        }
    };
}

define_id!(
    /// Identifies a single [`Graph Source`](crate::Source) within a
    /// [`Workspace`](crate::Workspace).
    ///
    /// Example: `"payment-local"`, `"account-remote"`.
    SourceId
);

define_id!(
    /// Identifies a [`Graph Workspace`](crate::Workspace) — the logical
    /// query context for one task (feature, bugfix, design review, etc.).
    ///
    /// Example: `"payment-feature"`.
    WorkspaceId
);

define_id!(
    /// Immutable graph-generation identifier returned by a GitNexus node
    /// after resolving `repo_id + branch`.
    ///
    /// Example: `"gen-17"`, `"gen-42"`.
    GenerationId
);

define_id!(
    /// Identifies a resolved, point-in-time view of a Workspace.
    ///
    /// Example: `"view-20260724-001"`.
    ViewId
);

define_id!(
    /// Identifies a [`QueryPlan`] generated by the Router for a given
    /// request.
    ///
    /// Example: `"plan-9281"`.
    PlanId
);

